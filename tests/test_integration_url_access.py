    def test_person_web_url_accessible(self) -> None:
        """
        GET /api/people → first item must have web_url matching .../people/{id},
        NOT .../photos/{id}.

        This is the live regression test for item 49: person objects decorated
        with /photos/{id} instead of /people/{id} produce 404 responses when
        accessed, because a person's UUID is not a valid asset ID.
        """
        raw = _request("GET", "/api/people", require_auth=True)

        # Immich wraps /api/people in {"people": [...], "hasNextPage": ...}
        if isinstance(raw, dict):
            items = raw.get("people") or []
        else:
            items = raw if isinstance(raw, list) else []

        if not items:
            self.skipTest("No people available in this Immich instance")

        decorated = _decorate_response(raw, self._external_domain, "array")

        # Extract the decorated people list from the (possibly) wrapped response
        if isinstance(decorated, dict):
            people = decorated.get("people") or []
        else:
            people = decorated if isinstance(decorated, list) else []

        if not people:
            self.skipTest("Decorated people list is empty")

        first = people[0]
        web_url = first.get("web_url")
        person_id = first.get("id", "")

        self.assertIsNotNone(web_url, "web_url field missing from decorated person response")

        # Regression check: must NOT be an asset URL (item 49 bug)
        self.assertNotRegex(
            web_url,
            rf".*/photos/{re.escape(person_id)}$",
            f"Person object received asset URL /photos/{{id}} — item 49 regression detected: {web_url}",
        )

        # Positive check: must be the correct person URL
        self.assertRegex(
            web_url,
            rf".*/people/{re.escape(person_id)}$",
            f"Person web_url has unexpected pattern (expected /people/{{id}}): {web_url}",
        )

        self._assert_web_url_accessible(web_url)

    def test_newest_image_search_web_url_accessible(self) -> None:
        """
        POST /api/search/assets with type=IMAGE and order=desc, page=1 →
        the newest image must have a web_url matching .../photos/{id} that is
        accessible (not 404).

        This exercises the full pipeline end-to-end: search endpoint → URL
        decoration of a wrapped search response → live HTTP access of the
        generated web_url.
        """
        search_body = {
            "type": "IMAGE",
            "order": "desc",
            "page": 1,
            "size": 1,
        }
        try:
            raw = _request(
                "POST",
                "/api/search/assets",
                json_body=search_body,
                require_auth=True,
            )
        except Exception as exc:
            self.skipTest(f"Could not search assets: {exc}")

        # Immich search response is wrapped:
        # {"assets": {"items": [...], "nextPage": null, "total": N, "count": N}}
        if isinstance(raw, dict):
            assets_wrapper = raw.get("assets")
            items = (
                assets_wrapper.get("items") or []
                if isinstance(assets_wrapper, dict)
                else []
            )
        else:
            items = raw if isinstance(raw, list) else []

        if not items:
            self.skipTest("Search returned no images")

        decorated_raw = _decorate_response(raw, self._external_domain, "array")

        # Extract decorated items from the wrapped structure
        if isinstance(decorated_raw, dict):
            assets_wrapper_dec = decorated_raw.get("assets")
            decorated_items = (
                assets_wrapper_dec.get("items") or []
                if isinstance(assets_wrapper_dec, dict)
                else []
            )
        else:
            decorated_items = decorated_raw if isinstance(decorated_raw, list) else []

        if not decorated_items:
            self.skipTest("Decorated search response contains no items")

        first = decorated_items[0]
        web_url = first.get("web_url")
        asset_id = re.escape(first.get("id", ""))

        self.assertIsNotNone(
            web_url, "web_url field missing from decorated search result"
        )
        self.assertRegex(
            web_url,
            rf".*/photos/{asset_id}$",
            f"Search result web_url has unexpected pattern: {web_url}",
        )

        self._assert_web_url_accessible(web_url)

    def test_random_person_web_url_accessible(self) -> None:
        """
        GET /api/people → pick a random person → assert web_url matches
        .../people/{id} and is accessible (not 404).
        Skipped if no people exist.
        """
        raw = _request("GET", "/api/people", require_auth=True)

        if isinstance(raw, dict):
            all_people = raw.get("people") or []
        else:
            all_people = raw if isinstance(raw, list) else []

        if not all_people:
            self.skipTest("No people available in this Immich instance")

        chosen = random.choice(all_people)
        decorated = _decorate_response(chosen, self._external_domain, "person")
        if not isinstance(decorated, dict):
            decorated = chosen

        person_id = chosen.get("id", "")
        web_url = decorated.get("web_url")

        self.assertIsNotNone(web_url, f"web_url missing for random person id={person_id}")
        self.assertRegex(
            web_url,
            rf".*/people/{re.escape(person_id)}$",
            f"Random person web_url has unexpected pattern: {web_url}",
        )
        self._assert_web_url_accessible(web_url)

